/** 최소 JPEG: SOI + APP0 + SOF0(가로·세로) + 채움 바이트 */
export function fakeJpeg(width: number, height: number, padding = 100): Uint8Array {
  const app0 = [0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00]
  const sof0 = [0xff, 0xc0, 0x00, 0x11, 0x08, height >> 8, height & 0xff, width >> 8, width & 0xff, 0x03, 1, 0x22, 0, 2, 0x11, 1, 3, 0x11, 1]
  return Uint8Array.from([0xff, 0xd8, ...app0, ...sof0, ...new Array(padding).fill(0), 0xff, 0xd9])
}
